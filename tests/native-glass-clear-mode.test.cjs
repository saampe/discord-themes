const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const bundle = fs.readFileSync("native-glass-clear-mode/index.js","utf8");
const manifest = JSON.parse(fs.readFileSync("native-glass-clear-mode/manifest.json","utf8"));
const ctx = {};
ctx.globalThis = ctx;
const instance = vm.runInNewContext(`((React) => { return ${bundle} })`, ctx)({});
assert.equal(typeof instance.start, "function");
assert.equal(manifest.version, "1.0.0");
assert.equal(ctx.__unboundGlassPreferences, undefined);
instance.start();
assert.equal(ctx.__unboundGlassPreferences.clearStyle, true);
instance.stop();
assert.equal("clearStyle" in ctx.__unboundGlassPreferences, false);
ctx.__unboundGlassPreferences.clearStyle = false;
instance.start();
assert.equal(ctx.__unboundGlassPreferences.clearStyle, true);
instance.stop();
assert.equal(ctx.__unboundGlassPreferences.clearStyle, false);
console.log("PASS native glass Clear preference is reversible and loadable by Unbound");
